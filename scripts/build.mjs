import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync, unlinkSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { zipSync, unzipSync } from 'fflate';
import { Resvg } from '@resvg/resvg-js';
import { resources } from './bundle.mjs';
import { optimizeToolbarPNG } from './toolbar-png.mjs';
const pkg = JSON.parse(readFileSync('package.json')), lock = JSON.parse(readFileSync('package-lock.json')), manifest = JSON.parse(readFileSync('src/mnaddon.json'));
if ([manifest.version, lock.version, lock.packages[''].version].some(version => version !== pkg.version)) throw new Error('三处版本不一致');
const release = process.argv.includes('--release');
if (release && pkg.version === '0.0.0') throw new Error('请等待用户指定正式版本');
const output = release ? `MN Pet-v${pkg.version}.mnaddon` : 'MN Pet Test.mnaddon';
if (release && existsSync(output)) throw new Error('正式包已存在，禁止覆盖');
const result = await resources();
const write = (path, bytes) => { const at = path.lastIndexOf('/'); if (at >= 0) mkdirSync(path.slice(0, at), { recursive: true }); writeFileSync(path, bytes); };
const artwork = readFileSync('assets/icon.png').toString('base64');
write('src/icon.png', new Resvg(`<svg xmlns="http://www.w3.org/2000/svg" width="48" height="48"><image width="48" height="48" href="data:image/png;base64,${artwork}"/></svg>`).render().asPng());
write('src/web-dist/settings.html', result.settingsHTML);
write('src/web-dist/focus.html', result.focusHTML);
// 清除旧构建生成的重复设置页面。
if (existsSync('src/web-dist/Resources.js')) unlinkSync('src/web-dist/Resources.js');
write('src/web-dist/pet-bubble/index.html', result.petBubbleHTML);
write('src/web-dist/pet-motion/index.html', result.petMotionHTML); write('src/web-dist/pet-motion/player.js', result.petMotionPlayer);
write('src/web-dist/pet-builtin/DSniang1.png', readFileSync('assets/pet/DSniang1-256.png'));
for (const name of ['SOURCE.md','UPSTREAM-PROVENANCE.md']) write('src/web-dist/pet-builtin/' + name, readFileSync('assets/pet/' + name));
for (const name of ['SOURCE.md','LICENSE']) write('src/web-dist/pet-bubble/' + name, readFileSync('assets/pet-bubble/' + name));
const close = readFileSync('assets/toolbar/x.svg', 'utf8').replace('stroke="currentColor"', 'stroke="#555555"');
write('src/web-dist/toolbar/close@3x.png', optimizeToolbarPNG(new Resvg(close, { fitTo: { mode: 'width', value: 60 } }).render().asPng()));
for (const name of ['SOURCE.md','LICENSE']) write('src/web-dist/toolbar/' + name, readFileSync('assets/toolbar/' + name));
write('src/web-dist/fflate-LICENSE.txt', readFileSync('node_modules/fflate/LICENSE'));
const files = {};
function collect(path, prefix = '') { for (const item of readdirSync(path, { withFileTypes: true })) { const name = prefix + item.name; if (item.isDirectory()) collect(path + '/' + item.name, name + '/'); else files[name] = new Uint8Array(readFileSync(path + '/' + item.name)); } }
collect('src');
if (files['web-dist/Resources.js']) throw new Error('安装包包含重复设置页面');
for (const name of ['main.js','icon.png',manifest.panel,'web-dist/focus.html','web-dist/pet-bubble/index.html','web-dist/pet-bubble/LICENSE','web-dist/pet-motion/player.js']) if (!files[name]) throw new Error('安装包缺少：' + name);
for (const match of readFileSync('src/main.js', 'utf8').matchAll(/JSB\.require\('([^']+)'\)/g)) if (!files[match[1] + '.js']) throw new Error('入口引用缺失：' + match[1]);
if (Object.keys(files).some(name => /AIB|Workflow|Upload|Notes|MediaReader|deepseek|doubao|gemini|gpt/i.test(name))) throw new Error('独立包包含无关 AI 模块');
const bytes = zipSync(files, { level: 9 }); writeFileSync(output, bytes);
const actual = unzipSync(readFileSync(output));
if (Object.keys(actual).length !== Object.keys(files).length) throw new Error('安装包文件数量不一致');
for (const [name, data] of Object.entries(files)) if (!actual[name] || !Buffer.from(actual[name]).equals(Buffer.from(data))) throw new Error('安装包与源码不一致：' + name);
console.log(JSON.stringify({ output, version: pkg.version, files: Object.keys(files).length, bytes: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') }, null, 2));
